const languageToggle = document.getElementById('languageToggle');
const pageTextNodes = [];
const textWalker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
let textNode;

while ((textNode = textWalker.nextNode())) {
    if (textNode.nodeValue.trim()) {
        pageTextNodes.push({ node: textNode, portuguese: textNode.nodeValue });
    }
}

const translatedAttributes = [];

Object.entries(attributeTranslations).forEach(([attribute, values]) => {
    document.querySelectorAll(`[${attribute}]`).forEach(element => {
        const portuguese = element.getAttribute(attribute);

        if (values[portuguese]) {
            translatedAttributes.push({ element, attribute, portuguese });
        }
    });
});

let currentLanguage = 'pt';

try {
    currentLanguage = localStorage.getItem('maurotur-language') === 'en' ? 'en' : 'pt';
} catch (error) {
    console.warn('Could not read the saved language preference.', error);
}

function setLanguage(language) {
    currentLanguage = language;
    const isEnglish = language === 'en';

    document.documentElement.lang = isEnglish ? 'en' : 'pt-BR';
    document.title = isEnglish
        ? 'MAUROTUR Transport and Tourism'
        : 'MAUROTUR Transporte e Turismo';

    pageTextNodes.forEach(({ node, portuguese }) => {
        if (!isEnglish) {
            node.nodeValue = portuguese;
            return;
        }

        const content = portuguese.trim().replace(/\s+/g, ' ');
        const translated = translations[content];

        if (translated) {
            const leadingSpace = portuguese.match(/^\s*/)[0];
            const trailingSpace = portuguese.match(/\s*$/)[0];
            node.nodeValue = `${leadingSpace}${translated}${trailingSpace}`;
        }
    });

    translatedAttributes.forEach(({ element, attribute, portuguese }) => {
        const values = attributeTranslations[attribute];
        element.setAttribute(attribute, isEnglish ? values[portuguese] : portuguese);
    });

    document.querySelectorAll('a[href*="wa.me"]').forEach(link => {
        const message = isEnglish
            ? 'Hello, I found you on the MAUROTUR website'
            : 'ola, vim do site maurotur';
        link.href = `https://wa.me/559884030572?text=${encodeURIComponent(message)}`;
    });

    if (languageToggle) {
        languageToggle.textContent = isEnglish ? 'Português' : 'English';
        languageToggle.setAttribute(
            'aria-label',
            isEnglish ? 'Switch the site language to Portuguese' : 'Mudar o idioma do site para inglês'
        );
        languageToggle.setAttribute('aria-pressed', String(isEnglish));
    }
}

if (languageToggle) {
    languageToggle.addEventListener('click', () => {
        const nextLanguage = currentLanguage === 'en' ? 'pt' : 'en';
        setLanguage(nextLanguage);

        try {
            localStorage.setItem('maurotur-language', nextLanguage);
        } catch (error) {
            console.warn('Could not save the language preference.', error);
        }
    });
}

setLanguage(currentLanguage);


