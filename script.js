// MODAL DA GALERIA
// ===============================

function openGalleryModal(src, alt) {

    if (!galleryModal || !galleryModalImage) {
        return;
    }

    galleryModalImage.src = src;
    galleryModalImage.alt = alt || 'Imagem ampliada';

    galleryModal.classList.add('is-open');

    galleryModal.setAttribute(
        'aria-hidden',
        'false'
    );

    document.body.style.overflow = 'hidden';
}


function closeGalleryModal() {

    if (!galleryModal) {
        return;
    }

    galleryModal.classList.remove('is-open');

    galleryModal.setAttribute(
        'aria-hidden',
        'true'
    );

    document.body.style.overflow = '';

    setTimeout(() => {

        if (galleryModalImage) {
            galleryModalImage.src = '';
        }

    }, 250);
}


// Clique nas imagens
galleryImages.forEach(image => {

    image.addEventListener('click', () => {

        openGalleryModal(
            image.src,
            image.alt
        );

    });


    // Teclado
    image.addEventListener('keydown', event => {

        if (
            event.key === 'Enter' ||
            event.key === ' '
        ) {

            event.preventDefault();

            openGalleryModal(
                image.src,
                image.alt
            );
        }

    });

});


// Fechar pelo botão
if (galleryModalClose) {

    galleryModalClose.addEventListener(
        'click',
        closeGalleryModal
    );

}


// Fechar clicando fora da imagem
if (galleryModal) {

    galleryModal.addEventListener('click', event => {

        if (event.target === galleryModal) {
            closeGalleryModal();
        }

    });

}


// Fechar com ESC
document.addEventListener('keydown', event => {

    if (
        event.key === 'Escape' &&
        galleryModal &&
        galleryModal.classList.contains('is-open')
    ) {
        closeGalleryModal();
    }

});